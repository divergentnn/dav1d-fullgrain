"""combine --rank-all outputs into the generic seed pool (av1fg_pool.inc)"""
import glob, sys
import numpy as np
files = sorted(glob.glob('r*.txt'), key=lambda f: int(f[1:-4]))
Z = []
for f in files:
    a = np.loadtxt(f)
    if len(a) != 65535: continue
    z = np.full(65536, 1e9); z[a[:, 0].astype(int)] = a[:, 1]
    Z.append(z)
Z = np.array(Z)
bad = (Z >= 1e8).any(0)
bad[0] = True
for s in range(65536):  # stripe offset generator at state 0 for frames up to 4320 rows
    for n in range(135):
        if s ^ (((n * 37 + 178) & 255) << 8) ^ ((n * 173 + 105) & 255) == 0: bad[s] = True
bad[0xb524] = bad[0x49d8] = True
avg = np.where(bad, 1e9, Z.mean(0))
# LFSR positions: neighbouring states share most of their template, so good seeds come in
# clusters; at most CAP seeds per 2048 positions keeps the pool spread over the whole cycle
pos = np.zeros(65536, np.int64); r = 1
for i in range(65535):
    pos[r] = i
    bit = (r ^ (r >> 1) ^ (r >> 3) ^ (r >> 12)) & 1
    r = (r >> 1) | (bit << 15)
N, CAP = 2048, 64
taken = np.zeros(32, int); sel = []
for sd in np.argsort(avg):
    if avg[sd] >= 1e8 or len(sel) == N:
        break
    if taken[pos[sd] // 2048] < CAP:
        taken[pos[sd] // 2048] += 1
        sel.append(sd)
order = np.array(sel)
print(f'{len(Z)} files; excluded {bad.sum()} degenerate seeds; pool of {len(order)}, worst mean z {avg[order].max():+.2f}')
for i, f in enumerate(files[:len(Z)]):
    z = Z[i]; valid = z < 1e8
    rank = np.argsort(np.argsort(np.where(valid, z, 1e9))) / valid.sum()
    pr = rank[order]
    print(f'  {f}: pool seeds in this file\'s best 2 %: {np.mean(pr < .02):.0%}, best 10 %: {np.mean(pr < .10):.0%}, median rank {np.median(pr)*100:.1f} %')
# sorted by position on the LFSR cycle: av1-grain-seed walks it with a stride of
# about 0.618 x the pool size, so the candidates of nearby frames come from far-apart
# parts of the cycle
pool = order[np.argsort(pos[order], kind='stable')]
with open(sys.argv[1], 'w') as fh:
    fh.write(f'/* {N} seeds with the lowest mean badness z-score over {len(Z)} files of real grain parameters,\n'
             f' * at most {CAP} per 2048 positions of the LFSR cycle\n'
             f' * (--rank-all; SVT-AV1, libaom, rav1e; 720p to 4K), sorted by LFSR position. Generated by\n'
             f' * tools/av1fg/tests/mkpool.py. */\n')
    for k in range(0, N, 12):
        fh.write('    ' + ', '.join(str(int(v)) for v in pool[k:k + 12]) + ',\n')

# reference seeds: 64 seeds at the quantiles (i + 0.5) / 64 of the mean z-score over all valid seeds, so
# the reference set spans the whole quality range evenly (a stratified sample; a plain sample of 64 or 32
# seeds can be noticeably luckier or unluckier than random and shifts every percentile)
if len(sys.argv) > 2:
    valid = np.where(avg < 1e8)[0]
    srt = valid[np.argsort(avg[valid], kind='stable')]
    refs = [int(srt[int((i + 0.5) / 64 * len(srt))]) for i in range(64)]
    with open(sys.argv[2], 'w') as fh:
        fh.write('/* 64 reference seeds at the quantiles (i + 0.5) / 64 of the mean badness z-score over the\n'
                 ' * --rank-all files (a stratified sample of seed quality), best first. Generated by\n'
                 ' * tools/av1fg/tests/mkpool.py. */\n')
        for k in range(0, 64, 8):
            fh.write('    ' + ', '.join(str(v) for v in refs[k:k + 8]) + ',\n')
    print('reference seeds: mean z', round(float(avg[refs].mean()), 3), 'vs all valid', round(float(avg[valid].mean()), 3))
